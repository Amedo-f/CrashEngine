    public static byte[] BuildPalette(int fogIndex)
    {
        int k = Math.Clamp(fogIndex, 0, PaletteCount - 1);
        var rgba = new byte[256 * 4];
        for (int i = 0; i < 256; i++)
        {
            var (r, g, b) = k == 0 ? (Violet[i * 3], Violet[i * 3 + 1], Violet[i * 3 + 2]) : Solid[k];
            rgba[i * 4]     = r;
            rgba[i * 4 + 1] = g;
            rgba[i * 4 + 2] = b;
            rgba[i * 4 + 3] = k == PaletteCount - 1 ? (byte)128 : Alpha[i];
        }
        return rgba;
    }

