    private static string Command(PS2BehaviourCommand m)
    {
        string? name = Enum.IsDefined(typeof(CommandId), m.CommandIndex) ? Enum.GetName(typeof(CommandId), m.CommandIndex) : null;
        if (name is not null && typeof(BehaviourCommands).GetMethod(name, BindingFlags.Public | BindingFlags.Static) is not null)
        {
            if (ReadableScript.ByOp.TryGetValue(m.CommandIndex, out var spec))
            {
                if (ReadableScript.DecodeParts(spec, m.Arguments.ToArray()) is { } parts)
                    return $"{name}({string.Join(", ", parts.Select(p => $"{Identifier(p.Name)}: {Value(p)}"))})";
            }
            else if (m.Arguments.Count == 0) return $"{name}()";
        }
        string args = m.Arguments.Count == 0 ? "" : ", " + string.Join(", ", m.Arguments.Select(a => $"0x{a:X}u"));
        return $"Cmd({Id<CommandId>(m.CommandIndex)}{args})";
    }

    // Amedo 2026-11-18
    private static string Value(ReadableScript.DecodedPart p)
    {
        string t = p.Text;
        if (p.Field is not { } f) return t + "u";
        switch (f.Kind)
        {
            case FieldKind.Variant:
                if (t.StartsWith("var(")) return $"ScriptValue.Var({t[4..^1]})";
                if (t.StartsWith("fvar(")) return $"ScriptValue.FVar({t[5..^1]})";
                if (t.StartsWith("raw(")) return $"ScriptValue.Raw({t[4..^1]}u)";
                return t;
            case FieldKind.Float:
                return t.StartsWith("raw(") ? $"FloatBits({t[4..^1]}u)" : t + "f";
            case FieldKind.Enum:
                return f.Names is not null && f.Names.ContainsValue(t) ? $"{f.EnumType}.{t}" : $"({f.EnumType}){t}";
            default:
                return t;
        }
    }

