using System.Globalization;
using System.Text;
using CrashEngine.Runtime.AgentLab;
using CrashEngine.Runtime.AgentLab.Compiled;
using Twinsanity.TwinsanityInterchange.Implementations.PS2.Items.RM2.Code.AgentLab;

namespace CrashEngine.ScriptGen;

// Amedo 2026-11-04: one behaviour script -> one C# class (stage 1, literal). Per state and body: the condition and the commands,
// each a fixed object with exactly the script's values (floats written as their bits), run through the same agent entry points
// (RunCondition / RunCommand) in the same order. The structure (jumps, packets, flags) still comes from the script data.
public static class BehaviourCodeGen
{
    public const string Namespace = "CrashEngine.Behaviours";

    public sealed record Output(string ClassName, string Folder, string Source, string Fingerprint);

    public static Output Generate(PS2BehaviourGraph graph, string className, IEnumerable<string> usedIn)
    {
        string fp = CompiledBehaviours.Fingerprint(graph);
        var fields = new StringBuilder();
        var conds = new StringBuilder();
        var cmds = new StringBuilder();
        for (int s = 0; s < graph.ScriptStates.Count; s++)
        {
            var st = (PS2BehaviourState)graph.ScriptStates[s];
            for (int b = 0; b < st.Bodies.Count; b++)
            {
                var body = (PS2BehaviourStateBody)st.Bodies[b];
                int key = s << 16 | b;
                string where = $"State_{s} body {b}";
                if (body.Condition is { } c)
                {
                    string name = $"C_{s}_{b}";
                    fields.AppendLine($"    private static readonly TwinBehaviourCondition {name} = Cond({c.ConditionIndex}, {c.Parameter}, {Bool(c.NotGate)}, {Bits(c.CheckInterval)}, {Bits(c.ReturnCheck)}, {Bits(c.ConditionPowerMultiplier)}); // {AgentLabWorld.ConditionName(c.ConditionIndex)}");
                    conds.AppendLine($"            case 0x{key:X}: return agent.RunCondition({name}, ctx); // {where}");
                }
                if (body.Commands.Count == 0) continue;
                cmds.AppendLine($"            case 0x{key:X}: // {where}");
                for (int i = 0; i < body.Commands.Count; i++)
                {
                    var m = (PS2BehaviourCommand)body.Commands[i];
                    string name = $"M_{s}_{b}_{i}";
                    string args = m.Arguments.Count == 0 ? "" : ", " + string.Join(", ", m.Arguments.Select(a => $"0x{a:X}u"));
                    fields.AppendLine($"    private static readonly PS2BehaviourCommand {name} = Cmd({m.CommandIndex}{args}); // {AgentLabWorld.CommandName(m.CommandIndex)}");
                    cmds.AppendLine($"                agent.RunCommand({name}, ctx);");
                }
                cmds.AppendLine("                return;");
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> CrashEngine.ScriptGen from the game's behaviour data. Made on your machine from your disc; do not share.");
        sb.AppendLine($"// {graph.Name}");
        sb.AppendLine($"// used in: {string.Join(", ", usedIn.Distinct().OrderBy(x => x, StringComparer.Ordinal))}");
        sb.AppendLine("using CrashEngine.Runtime.AgentLab;");
        sb.AppendLine("using CrashEngine.Runtime.AgentLab.Compiled;");
        sb.AppendLine("using Twinsanity.TwinsanityInterchange.Common.AgentLab;");
        sb.AppendLine("using Twinsanity.TwinsanityInterchange.Implementations.PS2.Items.RM2.Code.AgentLab;");
        sb.AppendLine();
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();
        sb.AppendLine($"public sealed class {className} : CompiledBehaviour");
        sb.AppendLine("{");
        sb.AppendLine($"    public override string Name => \"{graph.Name}\";");
        sb.AppendLine($"    public override string Fingerprint => \"{fp}\";");
        sb.AppendLine();
        sb.Append(fields);
        sb.AppendLine();
        sb.AppendLine("    public override float Condition(AgentLabAgent agent, int key, AgentLabAgent.Level ctx)");
        sb.AppendLine("    {");
        if (conds.Length > 0)
        {
            sb.AppendLine("        switch (key)");
            sb.AppendLine("        {");
            sb.Append(conds);
            sb.AppendLine("        }");
        }
        sb.AppendLine("        throw new InvalidOperationException($\"{Name}: no condition for 0x{key:X}\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public override void Commands(AgentLabAgent agent, int key, AgentLabAgent.Level ctx)");
        sb.AppendLine("    {");
        if (cmds.Length > 0)
        {
            sb.AppendLine("        switch (key)");
            sb.AppendLine("        {");
            sb.Append(cmds);
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return new Output(className, Naming.Folder(graph.Name), sb.ToString(), fp);
    }

    private static string Bool(bool b) => b ? "true" : "false";
    private static string Bits(float f) => "0x" + BitConverter.SingleToUInt32Bits(f).ToString("X", CultureInfo.InvariantCulture) + "u";
}
