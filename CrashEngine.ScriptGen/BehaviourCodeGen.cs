    private static string StateMethod(int state) => $"State{state}"; // Amedo 2026-11-18

    private static string When(TwinBehaviourCondition c) // Amedo 2026-11-18
    {
        var parts = new List<string> { Id<ConditionId>(c.ConditionIndex) };
        if (c.Parameter != 0) parts.Add(c.Parameter.ToString(CultureInfo.InvariantCulture));
        if (c.NotGate) parts.Add("not: true");
        if (Bits(c.CheckInterval) != Bits(0f)) parts.Add($"interval: {Float(c.CheckInterval)}");
        if (Bits(c.ReturnCheck) != Bits(0.5f)) parts.Add($"returnCheck: {Float(c.ReturnCheck)}");
        if (Bits(c.ConditionPowerMultiplier) != Bits(2f)) parts.Add($"power: {Float(c.ConditionPowerMultiplier)}");
        return $"When({string.Join(", ", parts)})";
    }

