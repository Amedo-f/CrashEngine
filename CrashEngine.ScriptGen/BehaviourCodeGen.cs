    private static string PacketCall(TwinBehaviourControlPacket p)
    {
        var parts = new List<string>();
        void E<T>(string name, T value) where T : struct, Enum
        {
            if (Convert.ToInt32(value) == 0) return;
            parts.Add(Enum.IsDefined(typeof(T), value) ? $"{name}: {typeof(T).Name}.{value}" : $"{name}: ({typeof(T).Name}){Convert.ToInt32(value)}");
        }
        void B(string name, bool value) { if (value) parts.Add($"{name}: true"); }
        E("space", p.Space); E("motion", p.Motion); E("rotate", p.ContinuousRotate); E("accel", p.AccelerationFunction);
        B("translates", p.Translates); B("rotates", p.Rotates); B("translationContinues", p.TranslationContinues); B("tracksDestination", p.TracksDestination);
        B("interpolatesAngles", p.InterpolatesAngles); B("yawFaces", p.YawFaces); B("pitchFaces", p.PitchFaces); B("orientsPredicts", p.OrientsPredicts);
        B("keyIsLocal", p.KeyIsLocal); B("usesRotator", p.UsesRotator); B("usesInterpolator", p.UsesInterpolator); B("usesPhysics", p.UsesPhysics);
        B("rotatesInWorldSpace", p.ContinuouslyRotatesInWorldSpace); E("axes", p.Axes); B("stalls", p.Stalls);
        var refs = new List<byte>();
        for (int i = 0; i < p.Bytes.Count; i++)
        {
            byte b = p.Bytes[i];
            if (b == 0xFF) continue;
            bool isInt = TwinBehaviourControlPacket.IsIntegerPacket((TwinBehaviourControlPacket.ControlPacketData)i);
            string v;
            if ((b & 0x80) != 0) v = $"{(isInt ? "PacketInteger" : "PacketNumber")}.Variable({b & 0x7F})";
            else
            {
                refs.Add(b);
                uint w = p.Floats[b];
                if (isInt) v = w <= int.MaxValue ? w.ToString(CultureInfo.InvariantCulture) : $"PacketInteger.Bits(0x{w:X}u)";
                else { v = Float(BitConverter.UInt32BitsToSingle(w)); if (v.StartsWith("FloatBits")) v = $"PacketNumber.Bits(0x{w:X}u)"; }
            }
            parts.Add($"{PacketFields[i]}: {v}");
        }
        if (refs.Where((r, k) => r != k).Any()) parts.Add($"order: [{string.Join(", ", refs)}]");
        return $"Packet({string.Join(", ", parts)})";
    }

