    private static string Float(float f)
    {
        string s = f.ToString("R", CultureInfo.InvariantCulture);
        bool exact = float.IsFinite(f) && !(f == 0f && float.IsNegative(f)) && Bits(float.Parse(s, CultureInfo.InvariantCulture)) == Bits(f);
        return exact ? s + "f" : $"FloatBits({Bits(f)})";
    }

    // Amedo 2026-11-18
    private static string Id<T>(ushort index) where T : struct, Enum =>
        Enum.IsDefined(typeof(T), index) ? $"{typeof(T).Name}.{Enum.GetName(typeof(T), index)}" : $"({typeof(T).Name}){index}";

    private static string Bits(float f) => "0x" + BitConverter.SingleToUInt32Bits(f).ToString("X", CultureInfo.InvariantCulture) + "u";
